CREATE TABLE working_menu_items
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category         VARCHAR(20)   NOT NULL CHECK (category IN ('VEG', 'NON_VEG')),
    subcategory      VARCHAR(100),
    name             VARCHAR(200)  NOT NULL,
    price_full       NUMERIC(10,2) NOT NULL,
    price_half       NUMERIC(10,2),
    offer_price_full NUMERIC(10,2),
    offer_price_half NUMERIC(10,2),
    offer_label      VARCHAR(100),
    is_override      BOOLEAN       NOT NULL DEFAULT FALSE,
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_working_menu_items_category ON working_menu_items (category);
CREATE INDEX idx_working_menu_items_active ON working_menu_items (active);