CREATE TABLE orders
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(200),
    customer_phone VARCHAR(50),
    status      VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'PREPARING', 'READY', 'DELIVERED', 'CANCELLED')),
    total_amount NUMERIC(10,2) NOT NULL DEFAULT 0,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_created_at ON orders (created_at);

CREATE TABLE order_items
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    menu_item_id    BIGINT NOT NULL,
    name            VARCHAR(200) NOT NULL,
    category        VARCHAR(20) NOT NULL,
    portion         VARCHAR(10) NOT NULL CHECK (portion IN ('FULL', 'HALF')),
    quantity        INTEGER NOT NULL DEFAULT 1,
    unit_price      NUMERIC(10,2) NOT NULL,
    total_price     NUMERIC(10,2) NOT NULL,
    offer_applied   BOOLEAN NOT NULL DEFAULT FALSE,
    offer_label     VARCHAR(100)
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);